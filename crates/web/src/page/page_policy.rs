use std::any::TypeId;
use std::fmt;
use std::marker::PhantomData;

use fundamental_authz::middleware::GuardCheck;
use fundamental_authz::schema::{Namespace, Relation};

use super::cache::Cache;
use super::guard_spec::GuardSpec;
use super::open::Open;
use super::page_title::PageTitle;
use super::pending_guard::PendingGuard;
use super::public_segment::PublicSegment;

/// The policy a `policy.rs` declares for every route at or below its directory; it only adds.
///
/// ```no_run
/// # use fundamental_macros::Namespace;
/// # use fundamental_web::{GuardedPolicy, PagePolicy};
/// # #[derive(Namespace)] enum User {}
/// # #[derive(Namespace)] enum Team { #[relation(direct(User))] Member }
/// # mod m { pub mod team {
/// #     // Generated by the crate's build from `locales/en/team.mf2`: a `Message`.
/// #     pub fn overview() -> impl std::fmt::Display + Send + Sync + 'static { "Overview" }
/// # } }
/// // pages/teams/[team]/policy.rs
/// pub fn policy() -> GuardedPolicy {
///     PagePolicy::new()
///         .signed_in()
///         .authorize(Team::Member)
///         .object("team")
///         .title(m::team::overview())
/// }
/// ```
#[must_use]
pub struct PagePolicy<G = Open> {
    pub(crate) signed_in: bool,
    pub(crate) guards: Vec<GuardSpec>,
    pub(crate) public_params: Vec<&'static str>,
    pub(crate) public_segments: Vec<(&'static str, TypeId)>,
    pub(crate) cache: Option<Cache>,
    pub(crate) title: Option<PageTitle>,
    state: PhantomData<fn() -> G>,
}

/// A policy that guards at least one object.
pub type GuardedPolicy = PagePolicy<super::guarded::Guarded>;

impl PagePolicy<Open> {
    /// A policy that declares nothing yet.
    pub fn new() -> Self {
        Self {
            signed_in: false,
            guards: Vec::new(),
            public_params: Vec::new(),
            public_segments: Vec::new(),
            cache: None,
            title: None,
            state: PhantomData,
        }
    }
}

impl Default for PagePolicy<Open> {
    fn default() -> Self {
        Self::new()
    }
}

impl<G> PagePolicy<G> {
    /// Requires a signed-in reader: anyone else is shown the gate, asked to sign in.
    pub fn signed_in(mut self) -> Self {
        self.signed_in = true;
        self
    }

    /// Requires the reader to hold `relation` on an object, named next with [`object`](PendingGuard::object).
    pub fn authorize<N>(self, relation: N) -> PendingGuard<G>
    where
        N: Namespace + Relation,
    {
        PendingGuard::new(self, GuardCheck::of(relation))
    }

    /// Declares the route parameter `name` public; refused at boot below a parameter guard (`FW_PAGE_005`).
    pub fn public_param(mut self, name: &'static str) -> Self {
        self.public_params.push(name);
        self
    }

    /// Declares the route parameter `name` a [`PublicSegment`] of type `T`.
    pub fn public_segment<T: PublicSegment>(mut self, name: &'static str) -> Self {
        self.public_segments.push((name, TypeId::of::<T>()));
        self
    }

    /// Declares how the pages may be cached; the strictest rule along the chain applies.
    pub fn cache(mut self, cache: Cache) -> Self {
        self.cache = Some(match self.cache {
            Some(declared) => declared.stricter(cache),
            None => cache,
        });
        self
    }

    /// The pages' title; the innermost along the chain is shown.
    pub fn title(mut self, title: impl fmt::Display + Send + Sync + 'static) -> Self {
        self.title = Some(PageTitle::new(title));
        self
    }

    pub(crate) fn with_guard<H>(mut self, guard: GuardSpec) -> PagePolicy<H> {
        self.guards.push(guard);
        self.retyped()
    }

    pub(crate) fn erased(self) -> PagePolicy<()> {
        self.retyped()
    }

    fn retyped<H>(self) -> PagePolicy<H> {
        PagePolicy {
            signed_in: self.signed_in,
            guards: self.guards,
            public_params: self.public_params,
            public_segments: self.public_segments,
            cache: self.cache,
            title: self.title,
            state: PhantomData,
        }
    }
}
