//! The `slugs!` macro: a page declares its own address in each language.

use proc_macro::TokenStream;
use quote::quote;
use syn::parse::{Parse, ParseStream};
use syn::{Ident, LitStr, Token};
use unicode_normalization::{UnicodeNormalization, is_nfc};

use crate::derives::core_path;

/// Whether `c` would be invisible in an address; checked here so the error lands at the span.
fn is_invisible(c: char) -> bool {
    c.is_whitespace()
        || c.is_control()
        || matches!(c,
            '\u{00ad}'
            | '\u{061c}'
            | '\u{180e}'
            | '\u{200b}'..='\u{200f}'
            | '\u{202a}'..='\u{202e}'
            | '\u{2060}'..='\u{2064}'
            | '\u{2066}'..='\u{2069}'
            | '\u{feff}'
        )
}

const CONST_NAME: &str = "PAGE_SLUGS";

const WORDS_NAME: &str = "WORD_SLUGS";

struct SlugEntry {
    language: String,
    slug: LitStr,
    retired: bool,
    language_span: proc_macro2::Span,
}

/// One `beneath "<word>" { … }` entry: a path word beneath the page that no page file names.
struct WordEntry {
    word: LitStr,
    entries: Vec<SlugEntry>,
}

struct SlugsInput {
    entries: Vec<SlugEntry>,
    words: Vec<WordEntry>,
}

fn peeks_keyword(input: ParseStream, keyword: &str) -> syn::Result<bool> {
    Ok(input.peek(Ident) && input.fork().parse::<Ident>()?.eq(keyword))
}

fn parse_entry(input: ParseStream) -> syn::Result<SlugEntry> {
    let retired = peeks_keyword(input, "retired")?;
    if retired {
        input.parse::<Ident>()?;
    }

    // Quoted languages are accepted only to refuse a regional tag with a readable message.
    let (language, language_span) = if input.peek(LitStr) {
        let literal: LitStr = input.parse()?;
        (literal.value(), literal.span())
    } else {
        let ident: Ident = input.parse()?;
        (ident.to_string(), ident.span())
    };

    input.parse::<Token![=]>()?;
    let slug: LitStr = input.parse()?;
    Ok(SlugEntry {
        language,
        slug,
        retired,
        language_span,
    })
}

fn parse_entries(input: ParseStream) -> syn::Result<Vec<SlugEntry>> {
    let mut entries = Vec::new();
    while !input.is_empty() {
        entries.push(parse_entry(input)?);
        if input.is_empty() {
            break;
        }
        input.parse::<Token![,]>()?;
    }
    Ok(entries)
}

impl Parse for SlugsInput {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let mut entries = Vec::new();
        let mut words = Vec::new();
        while !input.is_empty() {
            if peeks_keyword(input, "beneath")? {
                input.parse::<Ident>()?;
                let word: LitStr = input.parse()?;
                let content;
                syn::braced!(content in input);
                words.push(WordEntry {
                    word,
                    entries: parse_entries(&content)?,
                });
            } else {
                entries.push(parse_entry(input)?);
            }
            if input.is_empty() {
                break;
            }
            input.parse::<Token![,]>()?;
        }
        Ok(Self { entries, words })
    }
}

pub(crate) fn slugs(input: TokenStream) -> TokenStream {
    let parsed = match syn::parse::<SlugsInput>(input) {
        Ok(parsed) => parsed,
        Err(error) => return error.to_compile_error().into(),
    };
    if let Err(error) = validate(&parsed.entries) {
        return error.to_compile_error().into();
    }
    if let Err(error) = validate_words(&parsed.words) {
        return error.to_compile_error().into();
    }

    let core = core_path();
    let page_slugs = parsed.entries.iter().map(|entry| constructed(&core, entry));
    let words = parsed.words.iter().map(|word| {
        let stem = &word.word;
        let slugs = word.entries.iter().map(|entry| constructed(&core, entry));
        quote!((#stem, &[#(#slugs),*]))
    });
    let name = syn::Ident::new(CONST_NAME, proc_macro2::Span::call_site());
    let words_name = syn::Ident::new(WORDS_NAME, proc_macro2::Span::call_site());

    quote! {
        /// The path segments this page is addressed at, per language.
        ///
        /// Generated by `slugs!`; read by the surface's address registration.
        pub const #name: &[#core::address::PageSlug] = &[#(#page_slugs),*];

        /// The words directly beneath this page that no page file names, each with its
        /// spellings per language.
        ///
        /// Generated by `slugs!`; read by the surface's address registration.
        pub const #words_name: &[(&str, &[#core::address::PageSlug])] = &[#(#words),*];
    }
    .into()
}

fn constructed(core: &proc_macro2::TokenStream, entry: &SlugEntry) -> proc_macro2::TokenStream {
    let language = &entry.language;
    let slug = &entry.slug;
    match entry.retired {
        true => quote!(#core::address::PageSlug::retired(#language, #slug)),
        false => quote!(#core::address::PageSlug::current(#language, #slug)),
    }
}

/// Refuses a word beneath the page that is no one segment, declared twice, or misspelled as a page's would be.
fn validate_words(words: &[WordEntry]) -> syn::Result<()> {
    let mut seen: Vec<String> = Vec::new();
    for word in words {
        let stem = word.word.value();
        // Spelled as the route table spells a segment: a slug's rules, plus no capture braces.
        validate(&[SlugEntry {
            language: "und".to_owned(),
            slug: word.word.clone(),
            retired: false,
            language_span: word.word.span(),
        }])?;
        if stem.contains(['{', '}']) {
            return Err(syn::Error::new(
                word.word.span(),
                format!("`{stem}` is a capture; a word beneath a page is a fixed segment"),
            ));
        }
        if seen.contains(&stem) {
            return Err(syn::Error::new(
                word.word.span(),
                format!("`{stem}` is already declared beneath this page"),
            ));
        }
        if word.entries.is_empty() {
            return Err(syn::Error::new(
                word.word.span(),
                format!("`{stem}` declares no spelling; leave it out instead"),
            ));
        }
        validate(&word.entries)?;
        seen.push(stem);
    }
    Ok(())
}

/// Refuses every declaration that could not become an address, at the offending span.
#[expect(clippy::too_many_lines, reason = "readability baseline")]
fn validate(entries: &[SlugEntry]) -> syn::Result<()> {
    let mut seen: Vec<(&str, String)> = Vec::new();

    for entry in entries {
        let language = entry.language.as_str();

        if language.contains(['-', '_']) {
            return Err(syn::Error::new(
                entry.language_span,
                format!(
                    "`{language}` is a regional tag; a slug's language is the primary subtag only \
                     — write `{}`. Words belong to a language while a market belongs to an \
                     address, so one spelling serves every market that reads it.",
                    language.split(['-', '_']).next().unwrap_or(language)
                ),
            ));
        }
        if language.is_empty()
            || language.len() > 8
            || !language.bytes().all(|b| b.is_ascii_alphabetic())
        {
            return Err(syn::Error::new(
                entry.language_span,
                format!("`{language}` is not a language subtag: expected 1–8 ASCII letters"),
            ));
        }
        if language.bytes().any(|b| b.is_ascii_uppercase()) {
            return Err(syn::Error::new(
                entry.language_span,
                format!(
                    "write `{}` in lowercase: a locale's language subtag is lowercased, and an \
                     uppercase one would never match the request it is meant to serve",
                    language.to_ascii_lowercase()
                ),
            ));
        }

        let slug = entry.slug.value();
        if slug.is_empty() {
            return Err(syn::Error::new(
                entry.slug.span(),
                "a slug cannot be empty — it is one path segment",
            ));
        }
        if let Some(bad) = slug.chars().find(|c| matches!(c, '/' | '?' | '#')) {
            return Err(syn::Error::new(
                entry.slug.span(),
                format!(
                    "`{bad}` escapes the path segment: `/` starts the next one and `?`/`#` end \
                     the path, so `{slug}` could not be one page's address"
                ),
            ));
        }
        if slug.trim() != slug {
            return Err(syn::Error::new(
                entry.slug.span(),
                "a slug carries no leading or trailing whitespace — it would be invisible in the \
                 address bar and unreachable by anyone typing it",
            ));
        }
        if slug.contains('%') {
            return Err(syn::Error::new(
                entry.slug.span(),
                format!(
                    "`{slug}` is declared with a percent sign. A slug is the word a reader reads, \
                     and it is percent-encoded on its way into a URL — so this one would be \
                     served as `{}` and would name an address nobody meant. Write the character \
                     itself.",
                    slug.replace('%', "%25")
                ),
            ));
        }
        if let Some(invisible) = slug.chars().find(|c| is_invisible(*c)) {
            return Err(syn::Error::new(
                entry.slug.span(),
                format!(
                    "`{slug}` holds U+{:04X}, which an address bar does not show. An address is \
                     read before it is trusted: two slugs differing only by an invisible \
                     character look like one address and answer as two, and a bidi override \
                     reorders what is displayed without changing what resolves.",
                    u32::from(invisible)
                ),
            ));
        }
        if !is_nfc(&slug) {
            return Err(syn::Error::new(
                entry.slug.span(),
                format!(
                    "`{slug}` is not in Unicode normalization form C. The same word written two \
                     ways is two addresses that look identical, and an editor pasting from \
                     elsewhere is where the second one comes from. Write it as `{}`.",
                    slug.nfc().collect::<String>()
                ),
            ));
        }

        // The same word twice in one language: only one could ever be reached.
        if seen
            .iter()
            .any(|(seen_language, seen_slug)| *seen_language == language && *seen_slug == slug)
        {
            return Err(syn::Error::new(
                entry.slug.span(),
                format!("`{slug}` is already declared for `{language}` on this page"),
            ));
        }
        seen.push((language, slug));
    }

    // Two current spellings in one language would leave one of them dead.
    let mut current: Vec<&str> = Vec::new();
    for entry in entries.iter().filter(|entry| !entry.retired) {
        if current.contains(&entry.language.as_str()) {
            return Err(syn::Error::new(
                entry.language_span,
                format!(
                    "`{}` already has a current slug on this page — mark the older one `retired` \
                     so it keeps redirecting instead of competing",
                    entry.language
                ),
            ));
        }
        current.push(&entry.language);
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{SlugEntry, validate};
    use proc_macro2::Span;
    use syn::LitStr;

    fn entry(language: &str, slug: &str, retired: bool) -> SlugEntry {
        SlugEntry {
            language: language.to_string(),
            slug: LitStr::new(slug, Span::call_site()),
            retired,
            language_span: Span::call_site(),
        }
    }

    fn current(language: &str, slug: &str) -> SlugEntry {
        entry(language, slug, false)
    }

    fn refusal(entries: &[SlugEntry]) -> String {
        validate(entries)
            .expect_err("this declaration should be refused")
            .to_string()
    }

    #[test]
    fn an_ordinary_declaration_is_accepted() {
        assert!(
            validate(&[
                current("nl", "waarom"),
                current("sv", "varfor"),
                entry("nl", "waarom-acme", true),
            ])
            .is_ok()
        );
    }

    #[test]
    fn a_slug_in_the_languages_own_script_is_accepted() {
        assert!(
            validate(&[
                current("ja", "ログイン"),
                current("ru", "вход"),
                current("ar", "تسجيل-الدخول"),
                current("el", "σύνδεση"),
            ])
            .is_ok()
        );
    }

    #[test]
    fn a_percent_sign_is_refused_because_a_slug_is_the_decoded_form() {
        let message = refusal(&[current("ja", "%E3%83%AD")]);
        assert!(message.contains("percent-encoded"), "{message}");
    }

    #[test]
    fn a_slug_that_could_not_be_read_from_the_address_bar_is_refused() {
        for bad in ["log\u{200b}in", "\u{202e}nigol", "inlog\u{00ad}gen"] {
            let message = refusal(&[current("nl", bad)]);
            assert!(message.contains("address bar does not show"), "{message}");
        }
    }

    #[test]
    fn a_decomposed_spelling_is_refused_and_the_message_carries_the_composed_one() {
        let message = refusal(&[current("fr", "cre\u{0301}er")]);
        assert!(message.contains("normalization form C"), "{message}");
        assert!(message.contains("créer"), "{message}");
    }

    /// A regional tag would never match, silently doing nothing.
    #[test]
    fn a_regional_tag_is_refused_and_the_message_says_what_to_write() {
        let message = refusal(&[current("nl-BE", "waarom")]);
        assert!(message.contains("primary subtag"), "{message}");
        assert!(message.contains("`nl`"), "{message}");
    }

    #[test]
    fn an_uppercase_language_is_refused_because_it_could_never_match() {
        let message = refusal(&[current("NL", "waarom")]);
        assert!(message.contains("lowercase"), "{message}");
    }

    #[test]
    fn a_language_that_is_not_a_subtag_is_refused() {
        for bad in ["", "n1", "toolongtag"] {
            let message = refusal(&[current(bad, "waarom")]);
            assert!(message.contains("language subtag"), "{bad}: {message}");
        }
    }

    #[test]
    fn a_slug_that_escapes_its_segment_is_refused() {
        for bad in ["a/b", "a?b", "a#b"] {
            let message = refusal(&[current("nl", bad)]);
            assert!(
                message.contains("escapes the path segment"),
                "{bad}: {message}"
            );
        }
    }

    #[test]
    fn an_empty_slug_is_refused() {
        assert!(refusal(&[current("nl", "")]).contains("cannot be empty"));
    }

    #[test]
    fn a_slug_with_surrounding_whitespace_is_refused() {
        let message = refusal(&[current("nl", " waarom")]);
        assert!(message.contains("whitespace"), "{message}");
    }

    #[test]
    fn the_same_word_twice_in_one_language_is_refused() {
        let message = refusal(&[current("nl", "waarom"), current("nl", "waarom")]);
        assert!(message.contains("already declared"), "{message}");
    }

    #[test]
    fn two_current_slugs_for_one_language_are_refused_with_the_remedy() {
        let message = refusal(&[current("nl", "waarom"), current("nl", "waarvoor")]);
        assert!(message.contains("retired"), "{message}");
    }

    #[test]
    fn one_current_slug_beside_several_retired_ones_is_accepted() {
        assert!(
            validate(&[
                current("nl", "waarom"),
                entry("nl", "waarom-acme", true),
                entry("nl", "waaromacme", true),
            ])
            .is_ok()
        );
    }

    #[test]
    fn the_same_word_in_two_languages_is_accepted() {
        assert!(validate(&[current("nl", "trust"), current("de", "trust")]).is_ok());
    }

    fn word(stem: &str, entries: Vec<SlugEntry>) -> super::WordEntry {
        super::WordEntry {
            word: LitStr::new(stem, Span::call_site()),
            entries,
        }
    }

    fn word_refusal(words: &[super::WordEntry]) -> String {
        super::validate_words(words)
            .expect_err("these words should be refused")
            .to_string()
    }

    #[test]
    fn words_beneath_a_page_are_accepted() {
        assert!(
            super::validate_words(&[
                word("bedrijf", vec![current("en", "company")]),
                word("gebruikers", vec![current("en", "users")]),
            ])
            .is_ok()
        );
    }

    #[test]
    fn a_word_that_is_not_one_fixed_segment_is_refused() {
        for (bad, says) in [
            ("a/b", "escapes the path segment"),
            ("", "cannot be empty"),
            ("{step}", "is a capture"),
        ] {
            let message = word_refusal(&[word(bad, vec![current("en", "company")])]);
            assert!(message.contains(says), "{bad}: {message}");
        }
    }

    #[test]
    fn a_word_declared_twice_or_without_a_spelling_is_refused() {
        let twice = word_refusal(&[
            word("bedrijf", vec![current("en", "company")]),
            word("bedrijf", vec![current("en", "firm")]),
        ]);
        assert!(twice.contains("already declared beneath"), "{twice}");
        let bare = word_refusal(&[word("bedrijf", vec![])]);
        assert!(bare.contains("declares no spelling"), "{bare}");
    }

    #[test]
    fn a_words_spelling_is_refused_as_a_pages_would_be() {
        let message = word_refusal(&[word("bedrijf", vec![current("en", "com/pany")])]);
        assert!(message.contains("escapes the path segment"), "{message}");
    }
}
