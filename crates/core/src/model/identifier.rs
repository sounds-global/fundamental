//! Strongly-typed identifiers, generated with `#[derive(Identifier)]`.

/// A strongly-typed identifier wrapping a single inner value.
pub trait Identifier: Sized + Clone {
    /// The underlying storage type for this identifier (e.g. `uuid::Uuid`).
    type Inner;

    /// Creates an identifier from its inner value.
    fn from_inner(inner: Self::Inner) -> Self;

    /// Returns a reference to the inner value.
    fn as_inner(&self) -> &Self::Inner;

    /// Consumes the identifier and returns the inner value.
    fn into_inner(self) -> Self::Inner;
}

/// An [`Identifier`] that can mint fresh values, generated by `#[identifier(generate = …)]`.
pub trait GeneratedId: Identifier {
    /// Generates a new, unique identifier.
    fn generate() -> Self;
}
