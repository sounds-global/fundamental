//! Page-route registration for a tree that has a loader, a policy or a gate.
//!
//! The generated code only declares; `fundamental::web::PageRoute` serves each request in
//! one order: guards, loaders, render.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use super::page_gen::{
    emit_mod, emit_modules, emit_special_page, layout_idents, root_layout_wrapped,
};
use super::route::Route;
use super::route_fold::RouteFold;
use super::route_tree::RouteTree;

/// The state type a policy tree's registration is generated over.
const PAGE_STATE: &str = "crate::PageState";

/// The router a policy tree registers on, and what registering returns.
const ROUTER: &str = "::fundamental::web::Router<crate::PageState>";
const RESULT: &str =
    "::core::result::Result<::fundamental::web::Router<crate::PageState>, ::fundamental::AnyError>";

/// Render `register_pages` for a tree that serves the page state.
#[expect(clippy::too_many_lines, reason = "readability baseline")]
pub(crate) fn render_policy_registration(tree: &RouteTree, pages_dir: &Path) -> String {
    let mut out = String::new();
    out.push_str(
        "// @generated by fundamental_build — do not edit.\n\
         // This tree has a loader, a policy or a gate, so it is served over `crate::PageState`\n\
         // Declare `pub type PageState = <the app's state>;` at the crate root.\n",
    );

    let layouts = layout_idents(tree);
    emit_modules(&mut out, tree, pages_dir, &layouts);
    if let Some(gate) = &tree.gate {
        emit_mod(&mut out, "__gate", pages_dir, gate);
    }
    let policies = idents(&tree.policies, "__policy");
    for (path, ident) in &policies {
        emit_mod(&mut out, ident, pages_dir, path);
    }
    let loaders = idents(&tree.loaders, "__loader");
    for (path, ident) in &loaders {
        emit_mod(&mut out, ident, pages_dir, path);
    }

    let document = if tree.document.is_some() {
        "__document::document"
    } else {
        "::fundamental::web::default_document"
    };

    let _ = write!(
        out,
        "\n/// Register every page discovered under `pages/` as a server-rendered route, each \
         behind\n/// the policies at or above it.\n\
         ///\n\
         /// # Errors\n\
         ///\n\
         /// A route the router refuses, such as a path another page already registered, or a \
         policy\n/// chain `PageRoute` refuses.\n\
         pub fn register_pages(\n    router: {ROUTER},\n) -> {RESULT} {{\n",
    );
    let signature = format!("(__router: {ROUTER}) -> {RESULT} ");
    let fold = RouteFold {
        signature: &signature,
        turbofish: "",
    };
    fold.emit_fold(&mut out, tree.routes.len());
    let routes: Vec<String> = tree
        .routes
        .iter()
        .enumerate()
        .map(|(index, route)| {
            let chain = chain_expr(route, &policies);
            let served = served_expr(tree, index, route, &layouts, &loaders, document);
            format!(
                "::core::result::Result::Ok(__router.route(\n        \
                 ::fundamental::web::PageRoute::new(\n            \
                 {path:?},\n            \
                 {chain},\n        \
                 )?\n        \
                 {served},\n    \
                 )?)",
                path = route.url_path,
            )
        })
        .collect();

    if tree.not_found.is_some() {
        emit_special_page(
            &mut out,
            tree,
            &layouts,
            document,
            PAGE_STATE,
            "not_found",
            "__not_found",
        );
    }
    if tree.error_page.is_some() {
        emit_special_page(
            &mut out,
            tree,
            &layouts,
            document,
            PAGE_STATE,
            "error_page",
            "__error",
        );
    }
    if tree.gate.is_some() {
        let page = "__gate::page(__refused)";
        let wrapped = root_layout_wrapped(page, tree, &layouts);
        let view = if wrapped == page {
            "__gate::page".to_owned()
        } else {
            format!("|__refused| {wrapped}")
        };
        let _ = writeln!(
            out,
            "    let __router = __router.gate_page(::fundamental::web::PageRoute::gate(\n        \
             {view},\n        \
             {document},\n    \
             ));",
        );
    }
    out.push_str("    ::core::result::Result::Ok(__router)\n}\n");
    for (index, body) in routes.iter().enumerate() {
        fold.emit_route(&mut out, index, "", body);
    }
    out
}

fn idents(files: &[PathBuf], prefix: &str) -> BTreeMap<PathBuf, String> {
    files
        .iter()
        .enumerate()
        .map(|(i, file)| (file.clone(), format!("{prefix}_{i}")))
        .collect()
}

/// `PolicyChain::root().then("policy.rs", __policy_0::policy())…` for the route's chain.
fn chain_expr(route: &Route, policies: &BTreeMap<PathBuf, String>) -> String {
    let mut chain = "::fundamental::web::PolicyChain::root()".to_owned();
    for file in &route.policy_chain {
        let policy = module_fn(policies, file, "policy");
        let _ = write!(
            chain,
            "\n                    .then({:?}, {policy}())",
            file.to_string_lossy()
        );
    }
    chain
}

/// `<module>::<function>` for the module `file` was included as, or a `compile_error!` naming
/// the file if the scan and the includes disagree.
fn module_fn(modules: &BTreeMap<PathBuf, String>, file: &Path, function: &str) -> String {
    match modules.get(file) {
        Some(ident) => format!("{ident}::{function}"),
        None => format!(
            "compile_error!({:?})",
            format!(
                "fundamental_build: '{}' is in a route's chain but was not included",
                file.display()
            )
        ),
    }
}

/// The `.view(..)`, `.loaded(..)?` or `.with_data::<..>(..)` that serves the route.
#[expect(
    clippy::too_many_lines,
    clippy::too_many_arguments,
    reason = "readability baseline"
)]
fn served_expr(
    tree: &RouteTree,
    index: usize,
    route: &Route,
    layouts: &BTreeMap<&Path, String>,
    loaders: &BTreeMap<PathBuf, String>,
    document: &str,
) -> String {
    // The page's own loader first, then each framed layout's, outermost first: the tuple's order.
    let mut sources: Vec<(String, String)> = Vec::new();
    if let Some(file) = &route.loader {
        sources.push((
            file.to_string_lossy().into_owned(),
            module_fn(loaders, file, "load"),
        ));
    }
    let mut bindings: Vec<String> = Vec::new();
    if route.loader.is_some() {
        bindings.push("__model".to_owned());
    }
    let mut frames: BTreeMap<&Path, String> = BTreeMap::new();
    for layout_path in &route.layout_chain {
        let frame = tree
            .layouts
            .iter()
            .find(|layout| &layout.file_path == layout_path)
            .and_then(|layout| layout.frame.as_ref());
        if let Some(file) = frame {
            let binding = format!("__f{}", frames.len());
            frames.insert(layout_path.as_path(), binding.clone());
            bindings.push(binding);
            sources.push((
                file.to_string_lossy().into_owned(),
                module_fn(loaders, file, "frame"),
            ));
        }
    }

    let page = if route.loader.is_some() {
        format!("__page_{index}::page(__model)")
    } else {
        format!("__page_{index}::page()")
    };
    let mut view = page.clone();
    for layout_path in route.layout_chain.iter().rev() {
        if let Some(ident) = layouts.get(layout_path.as_path()) {
            view = match frames.get(layout_path.as_path()) {
                Some(frame) => format!("{ident}::layout({frame}, {view})"),
                None => format!("{ident}::layout({view})"),
            };
        }
    }

    if !sources.is_empty() {
        let loads: Vec<String> = sources
            .iter()
            .map(|(file, call)| format!("::fundamental::web::at({file:?}, {call})"))
            .collect();
        return format!(
            ".loaded(\n                ({},),\n                |({},)| {view},\n                {document},\n            )?",
            loads.join(", "),
            bindings.join(", "),
        );
    }

    // A bare `page` fn is passed as a path; a `|| page()` closure trips clippy.
    let view_arg = if view == page {
        format!("__page_{index}::page")
    } else {
        format!("|| {view}")
    };
    if route.loads_data {
        return format!(".with_data::<__page_{index}::Data, _, _, _, _>({view_arg}, {document})");
    }
    format!(".view({view_arg}, {document})")
}

#[cfg(test)]
mod tests {
    use super::render_policy_registration;
    use crate::route::RouteTree;
    use std::path::PathBuf;
    use tempfile::TempDir;

    fn tree_from(files: &[(&str, &str)]) -> (RouteTree, PathBuf) {
        let dir = TempDir::new().unwrap();
        for (rel, src) in files {
            let path = dir.path().join(rel);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent).unwrap();
            }
            std::fs::write(path, src).unwrap();
        }
        let tree = RouteTree::scan(dir.path()).unwrap();
        (tree, dir.keep())
    }

    const PAGE: &str = "pub fn page() {}";
    const LAYOUT: &str = "pub fn layout() {}";

    #[test]
    fn a_loader_page_registers_over_crate_page_state() {
        let (tree, dir) = tree_from(&[
            ("index.rs", PAGE),
            ("policy.rs", "pub fn policy() {}"),
            ("teams/[team]/index.rs", PAGE),
            ("teams/[team]/loader.rs", "pub async fn load() {}"),
        ]);
        let src = render_policy_registration(&tree, &dir);
        syn::parse_file(&src).expect("the registration parses");
        assert!(
            src.contains(
                "pub fn register_pages(\n    router: ::fundamental::web::Router<crate::PageState>"
            ),
            "{src}"
        );
        assert!(!src.contains("register_pages<S>"), "{src}");
        assert!(
            src.contains(".then(\"policy.rs\", __policy_0::policy())"),
            "{src}"
        );
        assert!(
            src.contains("::fundamental::web::at(\"teams/[team]/loader.rs\", __loader_0::load)"),
            "{src}"
        );
        assert!(
            src.contains("|(__model,)| __page_1::page(__model)"),
            "{src}"
        );
        assert!(
            src.contains(".view(__page_0::page, ::fundamental::web::default_document)"),
            "{src}"
        );
    }

    #[test]
    fn every_route_in_a_policy_tree_is_composed_even_with_no_policy_above_it() {
        let (tree, dir) = tree_from(&[
            ("about.rs", PAGE),
            ("teams/[team]/policy.rs", "pub fn policy() {}"),
            ("teams/[team]/index.rs", PAGE),
        ]);
        let src = render_policy_registration(&tree, &dir);
        assert_eq!(src.matches("PageRoute::new(").count(), 2, "{src}");
        assert_eq!(
            src.matches("::fundamental::web::PolicyChain::root()")
                .count(),
            2,
            "{src}"
        );
    }

    #[test]
    fn frames_are_handed_to_their_layouts_outermost_first() {
        let (tree, dir) = tree_from(&[
            ("layout.rs", LAYOUT),
            ("(app)/layout.rs", LAYOUT),
            ("(app)/loader.rs", "pub async fn frame() {}"),
            ("(app)/teams/[team]/layout.rs", LAYOUT),
            (
                "(app)/teams/[team]/loader.rs",
                "pub async fn load() {}\npub async fn frame() {}",
            ),
            ("(app)/teams/[team]/policy.rs", "pub fn policy() {}"),
            ("(app)/teams/[team]/index.rs", PAGE),
        ]);
        let src = render_policy_registration(&tree, &dir);
        syn::parse_file(&src).expect("the registration parses");
        assert!(
            src.contains("|(__model, __f0, __f1,)| __layout_0::layout(__layout_1::layout(__f0, __layout_2::layout(__f1, __page_0::page(__model))))"),
            "{src}"
        );
    }

    #[test]
    fn the_gate_is_registered_in_the_root_chain() {
        let (tree, dir) = tree_from(&[
            ("index.rs", PAGE),
            ("layout.rs", LAYOUT),
            ("error.rs", PAGE),
            ("gate.rs", PAGE),
            ("teams/layout.rs", LAYOUT),
            ("teams/index.rs", PAGE),
        ]);
        let src = render_policy_registration(&tree, &dir);
        syn::parse_file(&src).expect("the registration parses");
        assert!(
            src.contains("gate_page(::fundamental::web::PageRoute::gate(\n        |__refused| __layout_0::layout(__gate::page(__refused)),"),
            "only the root layout wraps the gate: {src}"
        );
    }

    #[test]
    fn a_data_page_under_a_policy_keeps_its_data() {
        let (tree, dir) = tree_from(&[
            ("policy.rs", "pub fn policy() {}"),
            ("devices.rs", "pub type Data = u8;\npub fn page() {}"),
        ]);
        let src = render_policy_registration(&tree, &dir);
        assert!(
            src.contains(".with_data::<__page_0::Data, _, _, _, _>(__page_0::page, ::fundamental::web::default_document)"),
            "{src}"
        );
    }

    #[test]
    fn a_framed_root_group_never_wraps_the_pages_that_load_nothing() {
        let (tree, dir) = tree_from(&[
            ("layout.rs", LAYOUT),
            ("(app)/layout.rs", LAYOUT),
            ("(app)/loader.rs", "pub async fn frame() {}"),
            ("(app)/index.rs", PAGE),
            ("error.rs", PAGE),
            ("not_found.rs", PAGE),
            ("gate.rs", PAGE),
        ]);
        let src = render_policy_registration(&tree, &dir);
        syn::parse_file(&src).expect("the registration parses");
        for special in [
            "__error::page()",
            "__not_found::page()",
            "__gate::page(__refused)",
        ] {
            assert!(
                src.contains(&format!("__layout_0::layout({special})")),
                "{special} wears only the root layout: {src}"
            );
        }
        assert!(!src.contains("__layout_1::layout(__error"), "{src}");
        assert!(!src.contains("__layout_1::layout(__gate"), "{src}");
        assert!(
            src.contains(
                "|(__f0,)| __layout_0::layout(__layout_1::layout(__f0, __page_0::page()))"
            ),
            "the group's own page still gets its frame: {src}"
        );
    }

    #[test]
    fn a_policy_the_includes_lost_fails_the_build_rather_than_vanishing() {
        let modules = std::collections::BTreeMap::new();
        let call = super::module_fn(&modules, std::path::Path::new("teams/policy.rs"), "policy");
        assert!(call.starts_with("compile_error!("), "{call}");
        assert!(call.contains("teams/policy.rs"), "{call}");
        syn::parse_str::<syn::Expr>(&format!("{call}()")).expect("still an expression");
    }
}
