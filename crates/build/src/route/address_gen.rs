//! Address-registration codegen for a [`RouteTree`]: a `page_slugs()` folding every page's
//! own `PAGE_SLUGS` into one [`SlugTable`](fundamental_core::address::SlugTable).
//!
//! No slug string is read here; the values come straight from each page's `slugs!` expansion.

use std::fmt::Write as _;
use std::path::Path;

use super::route_tree::RouteTree;

/// Render `page_slugs()` source for `tree`, whose files live under `pages_dir`.
///
/// It is `include!`d beside the page registration, which declares the modules it names.
#[must_use]
pub(crate) fn render_address_registration(tree: &RouteTree, pages_dir: &Path) -> String {
    let _ = pages_dir;
    let mut out = String::new();
    out.push_str("// @generated by fundamental_build — do not edit.\n");
    out.push_str(&slug_table(
        "::fundamental::web",
        "/// Every localized path segment the pages under `pages/` declared.\n\
         ///\n\
         /// # Errors\n\
         /// Returns [`AddressError`](::fundamental::web::AddressError) when two pages\n\
         /// would answer at one address — a surface must fail to boot rather than\n\
         /// serve whichever of them the resolver reaches first.\n",
        &table_entries(
            tree,
            |index| format!("__page_{index}"),
            |index| format!("__layout_{index}"),
        ),
    ));
    out
}

/// A `page_slugs()` that folds `entries` into a slug table, the types named from `root`.
///
/// The declarations are a constant the function walks, so it stays short for any page count.
pub(super) fn slug_table(root: &str, doc: &str, entries: &str) -> String {
    format!(
        "\n/// A page's or directory's path, its slugs and the words beneath it.\n\
         type __SlugDeclaration = (\n    &'static str,\n    &'static [{root}::PageSlug],\n    \
         &'static [(&'static str, &'static [{root}::PageSlug])],\n);\n\
         \n/// Every page and every directory that spells its own segment.\n\
         const __SLUG_DECLARATIONS: &[__SlugDeclaration] = &[{entries}\n];\n\
         \n{doc}\
         pub fn page_slugs() -> ::core::result::Result<{root}::SlugTable, {root}::AddressError> {{\n    \
         __SLUG_DECLARATIONS\n        \
         .iter()\n        \
         .fold({root}::SlugTable::builder(), |table, (path, slugs, words)| {{\n            \
         table.page(path, slugs).with_segments(path, words)\n        \
         }})\n        \
         .build()\n}}\n"
    )
}

/// The declarations of a slug table for `tree`, one `(path, slugs, words)` line each, for
/// the app's table and a routes crate's alike.
pub(super) fn table_entries(
    tree: &RouteTree,
    page_module: impl Fn(usize) -> String,
    layout_module: impl Fn(usize) -> String,
) -> String {
    let mut out = String::new();
    // Every page, not only declaring ones: a page's stem is what a sibling's slug must not shadow.
    for (index, route) in tree.routes.iter().enumerate() {
        let module = page_module(index);
        let slugs = match route.declares_slugs {
            true => format!("{module}::PAGE_SLUGS"),
            false => "&[]".to_string(),
        };
        // A hand-written `PAGE_SLUGS` has no words beside it; only `slugs!` declares them.
        let words = match route.slug_tokens {
            Some(_) => format!("{module}::WORD_SLUGS"),
            None => "&[]".to_string(),
        };
        let _ = write!(
            out,
            "\n    ({path:?}, {slugs}, {words}),",
            path = route.url_path
        );
    }

    // A layout spells its directory only where no `index.rs` does.
    for (index, layout) in tree.layouts.iter().enumerate() {
        if !layout.declares_slugs {
            continue;
        }
        let module = layout_module(index);
        let words = match layout.slug_tokens {
            Some(_) => format!("{module}::WORD_SLUGS"),
            None => "&[]".to_string(),
        };
        let _ = write!(
            out,
            "\n    ({prefix:?}, {module}::PAGE_SLUGS, {words}),",
            prefix = layout.url_prefix,
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;
    use tempfile::TempDir;

    const PAGE: &str = "pub fn page() {}";
    const WITH_SLUGS: &str = "slugs! { nl = \"waarom\" }\npub fn page() {}";

    fn tree_from(files: &[(&str, &str)]) -> (RouteTree, PathBuf) {
        let dir = TempDir::new().expect("temp dir");
        for (rel, src) in files {
            let path = dir.path().join(rel);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent).expect("create dir");
            }
            std::fs::write(path, src).expect("write page");
        }
        let canonical = std::fs::canonicalize(dir.path()).expect("canonical");
        let tree = RouteTree::scan(dir.path()).expect("scan");
        (tree, canonical)
    }

    #[test]
    fn generated_source_parses() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE), ("why.rs", WITH_SLUGS)]);
        let src = render_address_registration(&tree, &dir);
        syn::parse_file(&src).expect("generated address registration must parse");
    }

    /// The declaring page names its own constant; the values never pass through here.
    #[test]
    fn a_declaring_page_contributes_its_own_constant() {
        let (tree, dir) = tree_from(&[("why.rs", WITH_SLUGS)]);
        let src = render_address_registration(&tree, &dir);
        assert!(
            src.contains("(\"/why\", __page_0::PAGE_SLUGS, __page_0::WORD_SLUGS),"),
            "{src}"
        );
        assert!(
            !src.contains("waarom"),
            "the slug's value must not be read here: {src}"
        );
    }

    /// A page with no slugs is still declared, so a sibling's slug cannot shadow its stem.
    #[test]
    fn a_page_without_slugs_is_still_declared_so_it_can_be_protected() {
        let (tree, dir) = tree_from(&[("why.rs", WITH_SLUGS), ("trust.rs", PAGE)]);
        let src = render_address_registration(&tree, &dir);
        assert!(src.contains("(\"/trust\", &[], &[]),"), "{src}");
    }

    #[test]
    fn a_layout_may_carry_the_slug_for_a_directory_with_no_index() {
        let (tree, dir) = tree_from(&[
            (
                "guides/layout.rs",
                "slugs! { nl = \"gidsen\" }\npub fn layout<V>(v: V) -> V { v }",
            ),
            ("guides/api.rs", PAGE),
        ]);
        let src = render_address_registration(&tree, &dir);
        syn::parse_file(&src).expect("parses");
        assert!(
            src.contains("(\"/guides\", __layout_0::PAGE_SLUGS, __layout_0::WORD_SLUGS),"),
            "{src}"
        );
    }

    #[test]
    fn a_layout_without_slugs_contributes_nothing() {
        let (tree, dir) = tree_from(&[
            ("guides/layout.rs", "pub fn layout<V>(v: V) -> V { v }"),
            ("guides/api.rs", PAGE),
        ]);
        let src = render_address_registration(&tree, &dir);
        assert!(!src.contains("__layout_"), "{src}");
    }

    #[test]
    fn a_tree_with_no_slugs_builds_an_empty_table() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE), ("about.rs", PAGE)]);
        let src = render_address_registration(&tree, &dir);
        syn::parse_file(&src).expect("parses");
        assert!(!src.contains("PAGE_SLUGS"), "{src}");
        assert!(src.contains("(\"/\", &[], &[]),"));
        assert!(src.contains(".build()"));
    }

    #[test]
    fn an_empty_tree_still_builds_a_table() {
        let src = render_address_registration(&RouteTree::default(), Path::new("/pages"));
        syn::parse_file(&src).expect("parses");
        assert!(src.contains("SlugTable::builder()"));
        assert!(src.contains(".build()"));
    }

    /// The function stays as short with a hundred pages as with one.
    #[test]
    fn the_function_stays_short_however_many_pages_declare() {
        let names: Vec<String> = (0..40).map(|n| format!("page{n}.rs")).collect();
        let files: Vec<(&str, &str)> = names
            .iter()
            .map(|name| (name.as_str(), WITH_SLUGS))
            .collect();
        let (tree, dir) = tree_from(&files);
        let src = render_address_registration(&tree, &dir);
        syn::parse_file(&src).expect("parses");
        let body = src
            .lines()
            .skip_while(|line| !line.starts_with("pub fn page_slugs"))
            .take_while(|line| *line != "}")
            .count();
        assert!(body <= 12, "{body} lines: {src}");
    }

    /// The page indices line up with the ones `render_page_registration` emits.
    #[test]
    fn page_indices_match_the_page_registration() {
        let (tree, dir) = tree_from(&[
            ("index.rs", PAGE),
            ("why.rs", WITH_SLUGS),
            ("trust.rs", PAGE),
        ]);
        let addresses = render_address_registration(&tree, &dir);
        let pages = super::super::render_page_registration(&tree, &dir);

        let index_of_why = tree
            .routes
            .iter()
            .position(|route| route.url_path == "/why")
            .expect("the page is discovered");
        assert!(
            addresses.contains(&format!("__page_{index_of_why}::PAGE_SLUGS")),
            "{addresses}"
        );
        assert!(
            pages.contains(&format!("mod __page_{index_of_why};")),
            "the page registration must declare the module this names"
        );
    }
}
