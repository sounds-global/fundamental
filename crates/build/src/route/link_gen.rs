//! Typed link-builder generation for a [`RouteTree`].
//!
//! A builder takes each single-segment capture as `impl fundamental::address::PathSegment`,
//! which no raw id implements, and returns a [`PagePath`](fundamental_core::address::PagePath).

use std::collections::HashMap;
use std::fmt::Write as _;

use super::component_name::snake_basis;
use super::route::Route;
use super::route_tree::RouteTree;

/// Render typed link builders for `tree` as a self-contained Rust source string: `pub mod
/// routes` (one builder per route) and `pub mod params` (one struct per parameterized route).
#[must_use]
pub fn render_link_builders(tree: &RouteTree) -> String {
    let names = unique_fn_names(&tree.routes);

    let mut out = String::new();
    out.push_str("// @generated by fundamental_build — do not edit.\n");

    render_routes_module(tree, &names, &mut out);
    render_params_module(tree, &names, &mut out);
    out
}

/// Assign each route a unique snake_case fn name (suffixing `_2`, `_3` on clash).
fn unique_fn_names(routes: &[Route]) -> Vec<String> {
    let mut seen: HashMap<String, usize> = HashMap::new();
    let mut names = Vec::with_capacity(routes.len());
    for route in routes {
        let base = snake_basis(&route.url_path);
        let count = seen.entry(base.clone()).or_insert(0);
        *count += 1;
        if *count == 1 {
            names.push(base);
        } else {
            names.push(format!("{base}_{count}"));
        }
    }
    names
}

fn render_routes_module(tree: &RouteTree, names: &[String], out: &mut String) {
    out.push_str("\n/// Typed path builders, one per route.\npub mod routes {\n");
    for (route, name) in tree.routes.iter().zip(names) {
        render_route_fn(route, name, out);
    }
    out.push_str("}\n");
}

const PAGE_PATH: &str = "::fundamental::address::PagePath";

/// Emit one `pub fn <name>(...) -> PagePath` builder, `const` when it takes no capture.
fn render_route_fn(route: &Route, name: &str, out: &mut String) {
    let catch_all = |param: &str| route.url_path.contains(&format!("{{*{param}}}"));
    let args: String = route
        .params
        .iter()
        .map(|p| match catch_all(p) {
            true => format!("{p}: impl core::fmt::Display"),
            false => format!("{p}: impl ::fundamental::address::PathSegment"),
        })
        .collect::<Vec<_>>()
        .join(", ");

    let constness = if route.params.is_empty() {
        "const "
    } else {
        ""
    };
    let _ = writeln!(
        out,
        "    /// Build the path for `{}`.\n    #[must_use]\n    pub {constness}fn {name}({args}) -> {PAGE_PATH} {{",
        route.url_path
    );

    if route.params.is_empty() {
        let _ = writeln!(out, "        {PAGE_PATH}::of_route({:?})", route.url_path);
    } else {
        let format_str = link_format_string(route);
        let format_args: String = route
            .params
            .iter()
            .map(|p| match catch_all(p) {
                true => format!("{p} = {p}"),
                false => format!("{p} = ::fundamental::address::PathSegment::to_segment(&{p})"),
            })
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "        {PAGE_PATH}::of_built_route(format!({format_str:?}, {format_args}))"
        );
    }
    out.push_str("    }\n");
}

/// Turn a route URL into a `format!` template, dropping a catch-all's `*`.
fn link_format_string(route: &Route) -> String {
    route
        .url_path
        .split('/')
        .map(
            |seg| match seg.strip_prefix("{*").and_then(|s| s.strip_suffix('}')) {
                Some(param) => format!("{{{param}}}"),
                None => seg.to_string(),
            },
        )
        .collect::<Vec<_>>()
        .join("/")
}

fn render_params_module(tree: &RouteTree, names: &[String], out: &mut String) {
    out.push_str("\n/// Typed parameter structs, one per parameterized route.\npub mod params {\n");
    for (route, name) in tree.routes.iter().zip(names) {
        if route.params.is_empty() {
            continue;
        }
        let struct_name = format!("{}Params", to_pascal(name));
        let _ = writeln!(
            out,
            "    /// Parameters for `{}`.\n    #[derive(Debug, Clone, PartialEq, Eq)]\n    pub struct {struct_name} {{",
            route.url_path
        );
        for p in &route.params {
            let _ = writeln!(
                out,
                "        /// The `{p}` path parameter.\n        pub {p}: String,"
            );
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
}

fn to_pascal(snake: &str) -> String {
    snake
        .split('_')
        .filter(|w| !w.is_empty())
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().chain(chars).collect::<String>(),
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;
    use tempfile::TempDir;

    fn build_tree(files: &[(&str, &str)]) -> RouteTree {
        let d = TempDir::new().unwrap();
        for (rel, src) in files {
            let path = d.path().join(rel);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent).unwrap();
            }
            std::fs::write(path, src).unwrap();
        }
        RouteTree::scan(d.path()).unwrap()
    }

    #[test]
    fn generated_source_parses() {
        let tree = build_tree(&[
            ("index.rs", "pub fn page() {}"),
            ("about.rs", "pub fn page() {}"),
            ("users/[id].rs", "pub fn page() {}"),
            ("blog/[...slug].rs", "pub fn page() {}"),
        ]);
        let src = render_link_builders(&tree);
        syn::parse_file(&src).expect("generated link builders must parse");
    }

    #[test]
    fn contains_expected_signatures() {
        let tree = build_tree(&[
            ("index.rs", "pub fn page() {}"),
            ("about.rs", "pub fn page() {}"),
            ("users/[id].rs", "pub fn page() {}"),
        ]);
        let src = render_link_builders(&tree);
        assert!(src.contains("pub const fn index() -> ::fundamental::address::PagePath"));
        assert!(src.contains("pub const fn about() -> ::fundamental::address::PagePath"));
        assert!(src.contains(
            "pub fn users_id(id: impl ::fundamental::address::PathSegment) -> \
             ::fundamental::address::PagePath"
        ));
        assert!(src.contains("pub struct UsersIdParams"));
        assert!(src.contains("pub id: String,"));
    }

    #[test]
    fn static_route_returns_literal() {
        let tree = build_tree(&[("about.rs", "pub fn page() {}")]);
        let src = render_link_builders(&tree);
        assert!(src.contains("::fundamental::address::PagePath::of_route(\"/about\")"));
    }

    #[test]
    fn catch_all_builds_with_format() {
        let tree = build_tree(&[("blog/[...slug].rs", "pub fn page() {}")]);
        let src = render_link_builders(&tree);
        assert!(src.contains(
            "pub fn blog_slug(slug: impl core::fmt::Display) -> ::fundamental::address::PagePath"
        ));
        assert!(src.contains("/blog/{slug}"));
    }

    #[test]
    fn generated_file_writes_and_parses_from_disk() {
        let tree = build_tree(&[("users/[id].rs", "pub fn page() {}")]);
        let src = render_link_builders(&tree);
        let out = TempDir::new().unwrap();
        let path = out.path().join("links.rs");
        std::fs::write(&path, &src).unwrap();
        let read = std::fs::read_to_string(&path).unwrap();
        syn::parse_file(&read).expect("written file must parse");
        let _ = Path::new(&path);
    }

    #[test]
    fn no_params_means_no_params_struct() {
        let tree = build_tree(&[("about.rs", "pub fn page() {}")]);
        let src = render_link_builders(&tree);
        assert!(!src.contains("Params {"));
    }

    #[test]
    fn a_nested_dynamic_directory_builds_a_path_from_every_capture() {
        let tree = build_tree(&[(
            "[org]/projects/[project_id]/tasks/[task_id].rs",
            "pub fn page() {}",
        )]);
        let src = render_link_builders(&tree);
        assert!(
            src.contains(
                "pub fn org_projects_project_id_tasks_task_id(org: impl ::fundamental::address::PathSegment, \
                 project_id: impl ::fundamental::address::PathSegment, \
                 task_id: impl ::fundamental::address::PathSegment) -> \
                 ::fundamental::address::PagePath"
            ),
            "every capture must become an argument, in path order:\n{src}"
        );
        assert!(src.contains(
            "org = ::fundamental::address::PathSegment::to_segment(&org), \
             project_id = ::fundamental::address::PathSegment::to_segment(&project_id), \
             task_id = ::fundamental::address::PathSegment::to_segment(&task_id)"
        ));
    }

    /// Every `{name}` in a generated `format!` is named in that call's arguments, which
    /// `syn::parse_file` alone cannot see.
    #[test]
    fn every_capture_in_a_generated_format_is_supplied_as_an_argument() {
        let tree = build_tree(&[
            ("index.rs", "pub fn page() {}"),
            ("users/[id].rs", "pub fn page() {}"),
            ("blog/[...slug].rs", "pub fn page() {}"),
            ("[org]/projects/[project_id].rs", "pub fn page() {}"),
            ("[org]/settings.rs", "pub fn page() {}"),
        ]);
        let src = render_link_builders(&tree);

        for line in src
            .lines()
            .map(str::trim)
            .filter_map(|l| l.strip_prefix("::fundamental::address::PagePath::of_built_route("))
        {
            let (template, arguments) = line
                .split_once("\", ")
                .expect("a format! call carries a template and arguments");
            for capture in captures_of(template) {
                assert!(
                    arguments.contains(&format!("{capture} = ")),
                    "`{line}` interpolates {{{capture}}} but never supplies it"
                );
            }
        }
    }

    /// The `{name}` placeholders in a format template, `*` markers already removed.
    fn captures_of(template: &str) -> Vec<String> {
        template
            .split('{')
            .skip(1)
            .filter_map(|rest| rest.split_once('}'))
            .map(|(name, _)| name.trim_start_matches('*').to_string())
            .collect()
    }
}
