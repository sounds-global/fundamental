//! A surface's slug table for another crate: `page_slugs()` emitted into a routes crate,
//! expanded again from each page's own `slugs!` tokens.

use std::fmt::Write as _;
use std::path::Path;

use super::address_gen::{slug_table, table_entries};
use super::route_tree::RouteTree;

/// Render a self-contained `page_slugs()` for `tree`, to be `include!`d from `OUT_DIR`.
///
/// A hand-written `PAGE_SLUGS` has no tokens to copy, so its module is a `compile_error!`.
#[must_use]
pub fn render_page_slugs(tree: &RouteTree) -> String {
    let mut out = String::new();
    out.push_str("// @generated by fundamental_build — do not edit.\n");
    for (index, route) in tree.routes.iter().enumerate() {
        if route.declares_slugs {
            declaration(
                &mut out,
                &format!("__slugs_{index}"),
                route.slug_tokens.as_deref(),
                &route.module_path,
            );
        }
    }
    for (index, layout) in tree.layouts.iter().enumerate() {
        if layout.declares_slugs {
            declaration(
                &mut out,
                &format!("__layout_slugs_{index}"),
                layout.slug_tokens.as_deref(),
                &layout.file_path,
            );
        }
    }
    out.push_str(&slug_table(
        "::fundamental::address",
        "/// Every localized path segment the surface's pages declared, as its own\n\
         /// `page_slugs()` builds them.\n\
         ///\n\
         /// # Errors\n\
         /// Returns [`AddressError`](::fundamental::address::AddressError) when two pages\n\
         /// would answer at one address.\n",
        &table_entries(
            tree,
            |index| format!("__slugs_{index}"),
            |index| format!("__layout_slugs_{index}"),
        ),
    ));
    out
}

fn declaration(out: &mut String, module: &str, tokens: Option<&str>, file: &Path) {
    match tokens {
        Some(tokens) => {
            let _ = write!(
                out,
                "\nmod {module} {{\n    ::fundamental::slugs! {{ {tokens} }}\n}}\n"
            );
        }
        None => {
            let message = format!(
                "`{}` writes its PAGE_SLUGS by hand: a routes crate copies a page's addresses \
                 only from its `slugs!` declaration, so declare them with `slugs!`",
                file.display()
            );
            let _ = write!(
                out,
                "\nmod {module} {{\n    ::core::compile_error!({message:?});\n    \
                 pub(super) const PAGE_SLUGS: &[::fundamental::address::PageSlug] = &[];\n}}\n"
            );
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::route::address_gen::render_address_registration;
    use tempfile::TempDir;

    const PAGE: &str = "pub fn page() {}";

    fn tree_from(files: &[(&str, &str)]) -> RouteTree {
        let dir = TempDir::new().expect("temp dir");
        for (rel, src) in files {
            let path = dir.path().join(rel);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent).expect("create dir");
            }
            std::fs::write(path, src).expect("write page");
        }
        RouteTree::scan(dir.path()).expect("scan")
    }

    fn sample() -> RouteTree {
        tree_from(&[
            ("index.rs", PAGE),
            (
                "aanmelden/index.rs",
                "slugs! { en = \"sign-in\", beneath \"elders\" { en = \"elsewhere\" } }\n\
                 pub fn page() {}",
            ),
            (
                "bestand/layout.rs",
                "fundamental::slugs! { en = \"file\" }\npub fn layout<V>(v: V) -> V { v }",
            ),
            ("bestand/verlopen.rs", PAGE),
            (
                "[team]/facturen.rs",
                "slugs! { en = \"invoices\" }\npub fn page() {}",
            ),
        ])
    }

    #[test]
    fn generated_sibling_source_parses() {
        syn::parse_file(&render_page_slugs(&sample())).expect("generated page slugs must parse");
    }

    /// The sibling's table and the app's name the same pages and words; only the modules differ.
    #[test]
    fn the_sibling_table_names_the_same_pages_as_the_app_table() {
        let tree = sample();
        let entries = |source: &str| -> Vec<String> {
            source
                .lines()
                .map(str::trim)
                .filter(|line| line.starts_with("(\""))
                .map(|line| {
                    line.replace("__layout_slugs_", "L")
                        .replace("__layout_", "L")
                })
                .map(|line| line.replace("__slugs_", "P").replace("__page_", "P"))
                .collect()
        };
        let sibling = entries(&render_page_slugs(&tree));
        let app = entries(&render_address_registration(
            &tree,
            std::path::Path::new("."),
        ));
        assert_eq!(sibling, app);
        assert_eq!(sibling.len(), 5, "four pages and the layout: {sibling:?}");
        assert_eq!(
            sibling
                .iter()
                .filter(|line| line.contains("::WORD_SLUGS"))
                .count(),
            3,
            "the words beneath the three declarations: {sibling:?}"
        );
    }

    #[test]
    fn a_declaring_page_is_expanded_from_its_own_tokens() {
        let source = render_page_slugs(&sample());
        assert!(
            source.contains(
                "::fundamental::slugs! { en = \"sign-in\" , beneath \"elders\" { en = \"elsewhere\" } }"
            ),
            "{source}"
        );
        assert!(
            source.contains("::fundamental::slugs! { en = \"file\" }"),
            "{source}"
        );
        assert!(
            source.contains("(\"/{team}/facturen\", __slugs_"),
            "{source}"
        );
        assert!(source.contains("(\"/\", &[], &[]),"), "{source}");
        assert!(
            source
                .lines()
                .any(|line| line.trim().starts_with("(\"/aanmelden\", __slugs_")
                    && line.contains("::WORD_SLUGS")),
            "the words beneath a page come from its own declaration: {source}"
        );
    }

    #[test]
    fn a_hand_written_constant_cannot_be_copied() {
        let tree = tree_from(&[(
            "why.rs",
            "pub const PAGE_SLUGS: &[PageSlug] = &[];\npub fn page() {}",
        )]);
        let source = render_page_slugs(&tree);
        assert!(
            source.contains("::core::compile_error!(\"`why.rs` writes its PAGE_SLUGS by hand"),
            "{source}"
        );
        syn::parse_file(&source).expect("the refusal still parses");
        assert!(
            !source.contains("::WORD_SLUGS"),
            "a hand-written constant has no words beside it: {source}"
        );
    }
}
