//! Browser-entry codegen: the wasm `hydrate` export Leptos's island bootstrap calls.

use std::fmt::Write as _;
use std::path::Path;

use crate::hydration::Hydration;

use super::route_tree::RouteTree;

/// Render the browser hydration entry for `tree`, whose files live under `pages_dir`.
///
/// It includes every page and layout file so their islands compile into the bundle, then
/// a named `hydrate` export, which Leptos's bootstrap calls as `mod.hydrate()`.
/// [`Hydration::Live`] runs the app's `live_boot` first; [`Hydration::NoPages`] includes no
/// page module. `pages_dir` should be absolute.
#[must_use]
pub(crate) fn render_hydrate_entry(
    tree: &RouteTree,
    pages_dir: &Path,
    hydration: Hydration,
) -> String {
    if hydration == Hydration::NoPages {
        return render_hydrate_entry(&RouteTree::default(), pages_dir, Hydration::Plain);
    }
    let boot = hydration == Hydration::Live;
    let mut out = String::new();
    out.push_str("// @generated by fundamental_build — do not edit.\n\n");

    let mut index = 0;
    for route in &tree.routes {
        emit_mod(&mut out, index, pages_dir, &route.module_path);
        index += 1;
    }
    for layout in &tree.layouts {
        emit_mod(&mut out, index, pages_dir, &layout.file_path);
        index += 1;
    }
    // The 404 page is not a route, but an island in it must still hydrate.
    if let Some(not_found) = &tree.not_found {
        emit_mod(&mut out, index, pages_dir, not_found);
        index += 1;
    }
    // The gate too; `loader.rs` and `policy.rs` are server-only and never included.
    if let Some(gate) = &tree.gate {
        emit_mod(&mut out, index, pages_dir, gate);
        index += 1;
    }
    let _ = index;

    out.push_str(
        "\n/// Set up the hydration context; Leptos's island bootstrap calls this as\n\
         /// `mod.hydrate()`, then walks the DOM to hydrate each island.\n\
         #[::leptos::wasm_bindgen::prelude::wasm_bindgen]\n\
         pub fn hydrate() {\n",
    );
    out.push_str(if boot {
        "    ::fundamental::web::hydrate_with(|| crate::live_boot());\n"
    } else {
        "    ::fundamental::web::hydrate();\n"
    });
    out.push_str("}\n");
    out
}

/// Emit one `#[path = "<abs>"] mod __mod_<index>;` include, allowing dead code.
fn emit_mod(out: &mut String, index: usize, pages_dir: &Path, relative: &Path) {
    let absolute = pages_dir.join(relative);
    let _ = writeln!(
        out,
        "#[path = {:?}]\n#[allow(dead_code)]\nmod __mod_{index};",
        absolute.to_string_lossy()
    );
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;
    use tempfile::TempDir;

    fn tree_from(files: &[(&str, &str)]) -> (RouteTree, PathBuf) {
        let dir = TempDir::new().unwrap();
        for (rel, src) in files {
            let path = dir.path().join(rel);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent).unwrap();
            }
            std::fs::write(path, src).unwrap();
        }
        let tree = RouteTree::scan(dir.path()).unwrap();
        (tree, dir.keep())
    }

    const PAGE: &str = "pub fn page() {}";
    const LAYOUT: &str = "pub fn layout() {}";

    #[test]
    fn generated_entry_parses() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE), ("layout.rs", LAYOUT)]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::Plain);
        syn::parse_file(&src).expect("generated hydrate entry must parse");
    }

    #[test]
    fn hydrate_never_includes_a_loader_or_policy() {
        let (tree, dir) = tree_from(&[
            ("index.rs", PAGE),
            ("policy.rs", "pub fn policy() {}"),
            ("error.rs", PAGE),
            ("gate.rs", PAGE),
            ("teams/index.rs", PAGE),
            ("teams/loader.rs", "pub async fn load() {}"),
            ("teams/policy.rs", "pub fn policy() {}"),
        ]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::Plain);
        assert!(!src.contains("loader.rs"), "{src}");
        assert!(!src.contains("policy.rs"), "{src}");
        assert!(
            src.contains("gate.rs"),
            "the gate's islands must hydrate: {src}"
        );
        assert!(!src.contains("error.rs"), "{src}");
        assert_eq!(src.matches("mod __mod_").count(), 3);
    }

    #[test]
    fn includes_one_module_per_page_and_layout() {
        let (tree, dir) = tree_from(&[
            ("index.rs", PAGE),
            ("about.rs", PAGE),
            ("layout.rs", LAYOUT),
        ]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::Plain);
        assert_eq!(src.matches("#[path =").count(), 3);
        assert_eq!(src.matches("mod __mod_").count(), 3);
    }

    #[test]
    fn defines_a_named_hydrate_export() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE)]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::Plain);
        assert!(src.contains("pub fn hydrate()"), "src: {src}");
        assert!(!src.contains("(start)"), "must not be a start fn: {src}");
        assert!(src.contains("::fundamental::web::hydrate()"));
    }

    #[test]
    fn boot_entry_calls_hydrate_with_the_app_bootstrap() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE)]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::Live);
        syn::parse_file(&src).expect("generated boot entry must parse");
        assert!(
            src.contains("::fundamental::web::hydrate_with(|| crate::live_boot())"),
            "src: {src}"
        );
        assert!(!src.contains("::fundamental::web::hydrate()"), "src: {src}");
    }

    #[test]
    fn a_site_without_script_hydrates_no_page() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE), ("layout.rs", LAYOUT)]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::NoPages);
        assert_eq!(
            src,
            render_hydrate_entry(&RouteTree::default(), &dir, Hydration::Plain)
        );
        assert_eq!(src.matches("#[path =").count(), 0);
        assert!(src.contains("pub fn hydrate()"));
    }

    #[test]
    fn empty_tree_still_emits_the_export() {
        let src =
            render_hydrate_entry(&RouteTree::default(), Path::new("/pages"), Hydration::Plain);
        syn::parse_file(&src).expect("parses");
        assert!(src.contains("pub fn hydrate()"));
        assert_eq!(src.matches("#[path =").count(), 0);
    }

    /// An island inside the 404 page reaches the browser bundle.
    #[test]
    fn the_not_found_page_is_compiled_into_the_bundle() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE), ("not_found.rs", PAGE)]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::Plain);
        syn::parse_file(&src).expect("parses");
        assert_eq!(
            src.matches("#[path =").count(),
            2,
            "the page and the 404 page both:\n{src}"
        );
        assert!(src.contains("not_found.rs"));
    }

    #[test]
    fn a_tree_without_a_not_found_page_emits_what_it_always_did() {
        let (tree, dir) = tree_from(&[("index.rs", PAGE)]);
        let src = render_hydrate_entry(&tree, &dir, Hydration::Plain);
        assert_eq!(src.matches("#[path =").count(), 1);
    }
}
